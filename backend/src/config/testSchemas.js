export function getTestSchemaByIdOrName(identifier) {
  if (!identifier) return TEST_SCHEMAS.specific_ige;
  const clean = identifier.toLowerCase().trim();

  for (const schema of Object.values(TEST_SCHEMAS)) {
    if (schema.id.toLowerCase() === clean) return schema;
    if (schema.name.toLowerCase() === clean) return schema;
    if (schema.shortName.toLowerCase() === clean) return schema;
    if (schema.standardTestTypeName.toLowerCase() === clean) return schema;
  }

  // Fuzzy matches
  if (clean.includes('skin prick') || clean.includes('spt')) return TEST_SCHEMAS.skin_prick;
  if (clean.includes('component') || clean.includes('crd')) return TEST_SCHEMAS.crd;
  if (clean.includes('challenge') || clean.includes('ofc')) return TEST_SCHEMAS.oral_challenge;
  if (clean.includes('total ige')) return TEST_SCHEMAS.total_ige;
  if (clean.includes('basophil') || clean.includes('bat')) return TEST_SCHEMAS.bat;
  if (clean.includes('patch')) return TEST_SCHEMAS.patch_test;
  if (clean.includes('intradermal')) return TEST_SCHEMAS.intradermal;
  if (clean.includes('blood') || clean.includes('ige')) return TEST_SCHEMAS.specific_ige;

  return TEST_SCHEMAS.specific_ige;
}
